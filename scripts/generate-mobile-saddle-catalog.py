#!/usr/bin/env python3
"""Generate/check mobile saddle membership from a public server checkout.

Usage: python3 scripts/generate-mobile-saddle-catalog.py SERVER_ROOT [--check]
Only game_item_saddles INSERT rows in migrations 37 and 40 are authoritative.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "Assets/FakeFantasyOnline/Runtime/Presentation/ReferenceAssets/MobileSaddleCatalog.cs"
SOURCE = "fake-fantasy-online-group/fake-fantasy-online-server"


def saddle_ids(server_root):
    ids = []
    for migration in (37, 40):
        path = server_root / f"server/migrations/000000_init-{migration}.sql"
        sql = path.read_text(encoding="utf-8")
        blocks = re.findall(
            r"INSERT\s+INTO\s+game_item_saddles\s*\(\s*item_id\s*,[^;]*?\)\s*VALUES\s*(.*?);",
            sql, re.IGNORECASE | re.DOTALL)
        if len(blocks) != 1:
            raise ValueError(f"Expected exactly one saddle INSERT in {path}")
        # These migration rows contain only integer/boolean values. Reject a changed
        # SQL shape rather than silently generating a partial classification.
        rows = re.findall(r"\(\s*(\d+)\s*,\s*\d+\s*,\s*\d+\s*,\s*\d+\s*,\s*(?:TRUE|FALSE)(?:\s*,\s*(?:TRUE|FALSE))?\s*\)",
                          blocks[0], re.IGNORECASE)
        residual = re.sub(r"\([^()]*\)", "", blocks[0]).replace(",", "").strip()
        if not rows or residual or len(rows) != blocks[0].count("("):
            raise ValueError(f"Unexpected saddle VALUES syntax in {path}")
        ids.extend(int(value) for value in rows)
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate saddle IDs across migrations")
    return sorted(ids)


def render(ids):
    cases = "\n".join(f"            case {value}:" for value in ids)
    return f"""// Generated by scripts/generate-mobile-saddle-catalog.py; do not edit by hand.
// Source: https://github.com/{SOURCE}
// server/migrations/000000_init-37.sql and 000000_init-40.sql:
// exact game_item_saddles INSERT item_id values ({len(ids)} IDs).
// Classification only: never selects a saddle or matches it to a pet.
namespace FakeFantasyOnline.Presentation.ReferenceAssets
{{
internal static class MobileSaddleCatalog
{{
    internal static bool Contains(int id)
    {{
        switch (id)
        {{
{cases}
                return true;
            default:
                return false;
        }}
    }}
}}
}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("server_root", type=Path)
    parser.add_argument("--check", action="store_true", help="Verify the checked-in catalog without writing")
    args = parser.parse_args()
    ids = saddle_ids(args.server_root)
    expected = render(ids)
    if args.check:
        if TARGET.read_text(encoding="utf-8") != expected:
            parser.error("MobileSaddleCatalog.cs differs from authoritative saddle IDs; regenerate it")
        print(f"PASS: MobileSaddleCatalog matches all {len(ids)} authoritative saddle IDs")
    else:
        TARGET.write_text(expected, encoding="utf-8")
        print(f"Generated MobileSaddleCatalog with {len(ids)} authoritative saddle IDs")


if __name__ == "__main__":
    main()
