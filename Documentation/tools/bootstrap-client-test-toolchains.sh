#!/usr/bin/env bash
# Recover engine-free C# test tools only. Does not install or invoke Unity.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="${1:-${FFO_CLIENT_TOOLCHAIN_HOME:-$HOME/.cache/ffo/client-toolchains}}"
for tool in python3 curl dpkg-deb unzip; do command -v "$tool" >/dev/null || { echo "Missing prerequisite: $tool" >&2; exit 1; }; done
[[ "$(uname -s)/$(uname -m)" == Linux/x86_64 ]] || { echo 'This locked bootstrap targets Debian-compatible Linux x86_64.' >&2; exit 1; }
mkdir -p "$ROOT"; ROOT="$(cd "$ROOT" && pwd)"
python3 - "$HERE/mono-debian-packages.lock.json" "$ROOT" <<'PY'
import concurrent.futures
import hashlib
import json
from pathlib import Path
import subprocess
import sys

lock, root = Path(sys.argv[1]), Path(sys.argv[2])
cache = root / "downloads"
cache.mkdir(exist_ok=True)

def download(url, filename, sha256):
    target = cache / filename
    if target.exists():
        if hashlib.sha256(target.read_bytes()).hexdigest() != sha256:
            raise RuntimeError(f"Cached file hash mismatch: {target}; inspect/remove it before retrying")
        return target
    partial = target.with_suffix(target.suffix + ".partial")
    subprocess.run(["curl", "--fail", "--location", "--silent", "--show-error", "--max-time", "180", url, "-o", str(partial)], check=True)
    if hashlib.sha256(partial.read_bytes()).hexdigest() != sha256:
        raise RuntimeError(f"Downloaded file hash mismatch: {partial}")
    partial.replace(target)
    return target

packages = json.loads(lock.read_text())
def fetch_package(package):
    return download("https://deb.debian.org/debian/" + package["Filename"], Path(package["Filename"]).name, package["SHA256"])
with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
    paths = list(pool.map(fetch_package, packages))
for path in paths:
    # Extract into a private prefix; do not invoke package maintainer scripts.
    subprocess.run(["dpkg-deb", "-x", str(path), str(root / "mono-debian")], check=True)

nuget_packages = [
    ("microsoft.net.compilers.toolset", "4.8.0", "37333f4f1e2ce55e621355d6da651dc23d4cb5f94a8f76b9478816e87f110ad9", "roslyn-4.8.0"),
]
for package, version, digest, directory in nuget_packages:
    filename = f"{package}.{version}.nupkg"
    archive = download(f"https://api.nuget.org/v3-flatcontainer/{package}/{version}/{filename}", filename, digest)
    subprocess.run(["unzip", "-q", "-o", str(archive), "-d", str(root / directory)], check=True)
# Mono's packaged 4.7.2-api reference profile matches these engine-free tests.
# Microsoft's Windows reference package additionally carries native COM+
# modules, which cannot all be passed as managed references by these scripts.
assert (root / "mono-debian/usr/lib/mono/4.7.2-api/mscorlib.dll").is_file()
print(f"Verified and extracted {len(packages)} Debian Mono packages (including 4.7.2-api refs) and official Microsoft Roslyn.")
PY

{
 printf '# Generated by bootstrap-client-test-toolchains.sh; source this file in Bash.\n'
 printf 'export FFO_CLIENT_TOOLCHAIN_HOME=%q\n' "$ROOT"
 cat <<'ENV'
export FFO_MONO_ROOT="$FFO_CLIENT_TOOLCHAIN_HOME/mono-debian/usr"
export FFO_CSC="$FFO_CLIENT_TOOLCHAIN_HOME/roslyn-4.8.0/tasks/net472/csc.exe"
export FFO_FRAMEWORK_DIR="$FFO_MONO_ROOT/lib/mono/4.7.2-api"
export FFO_COMPILE_DIR="${FFO_COMPILE_DIR:-$FFO_CLIENT_TOOLCHAIN_HOME/managed-compile}"
export MONO_CFG_DIR="$FFO_CLIENT_TOOLCHAIN_HOME/mono-debian/etc"
export MONO_GAC_PREFIX="$FFO_MONO_ROOT"
export PATH="$FFO_MONO_ROOT/bin:$PATH"
ENV
} > "$ROOT/env.sh"
source "$ROOT/env.sh"
"$FFO_MONO_ROOT/bin/mono" --version
"$FFO_MONO_ROOT/bin/mono" "$FFO_MONO_ROOT/lib/mono/4.5/mcs.exe" --version
"$FFO_MONO_ROOT/bin/mono" "$FFO_CSC" -version
printf 'Ready. Run: source %q\n' "$ROOT/env.sh"
